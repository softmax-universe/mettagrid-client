#!/usr/bin/env bun

/**
 * Build a low-res sprite atlas from MettaScope assets.
 * Downscales all game sprites to target size and packs into a single PNG + JSON manifest.
 */

import sharp from 'sharp'
import { readdir, writeFile, mkdir } from 'fs/promises'
import { existsSync } from 'fs'
import { join, basename } from 'path'

const METTASCOPE_DATA = process.argv[2] || join(
  import.meta.dir, '..', '..', '..', 'metta', 'packages', 'mettagrid', 'nim', 'mettascope', 'data'
)
const OUTPUT_DIR = join(import.meta.dir, '..', 'src', 'sprites')
const TILE_SIZE = 24
const COLS = 16

interface SpriteEntry {
  name: string
  x: number
  y: number
  w: number
  h: number
  category: string
}

interface SpriteSource {
  path: string
  name: string
  category: string
}

async function findSprites (): Promise<SpriteSource[]> {
  const sources: SpriteSource[] = []

  const agentDir = join(METTASCOPE_DATA, 'agents')
  const objectDir = join(METTASCOPE_DATA, 'objects')
  const resourceDir = join(METTASCOPE_DATA, 'resources')

  // Agents: east-facing only (we'll rotate in renderer if needed)
  const agentNames = ['agent', 'miner', 'scout', 'scrambler', 'aligner', 'chef', 'miner_pickaxe']
  for (const name of agentNames) {
    const path = join(agentDir, `${name}.e.png`)
    if (existsSync(path)) sources.push({ path, name: `agent_${name}`, category: 'agent' })
    const maskPath = join(agentDir, `${name}.e.mask.png`)
    if (existsSync(maskPath)) sources.push({ path: maskPath, name: `agent_${name}_mask`, category: 'agent_mask' })
  }

  // Frozen overlay
  const frozenPath = join(agentDir, 'frozen.png')
  if (existsSync(frozenPath)) sources.push({ path: frozenPath, name: 'frozen', category: 'effect' })

  // Objects
  const objectNames = [
    'hub', 'hub.ready', 'hub.working',
    'junction', 'junction.working', 'junction.depleted',
    'carbon_extractor', 'germanium_extractor', 'oxygen_extractor', 'silicon_extractor',
    'carbon_extractor.working', 'germanium_extractor.working', 'oxygen_extractor.working', 'silicon_extractor.working',
    'charger', 'generator', 'chest', 'block', 'ship',
    'armory', 'lab', 'factory', 'temple', 'altar',
    'converter', 'trash', 'unknown',
    'selection',
  ]
  for (const name of objectNames) {
    const path = join(objectDir, `${name}.png`)
    if (existsSync(path)) sources.push({ path, name: `obj_${name.replace(/\./g, '_')}`, category: 'object' })
  }

  // Resources
  const resourceNames = [
    'heart', 'carbon', 'germanium', 'oxygen', 'silicon',
    'energy', 'ore', 'battery', 'laser', 'armor',
    'blueprint', 'decoder', 'modulator', 'resonator', 'star',
  ]
  for (const name of resourceNames) {
    const path = join(resourceDir, `${name}.png`)
    if (existsSync(path)) sources.push({ path, name: `res_${name}`, category: 'resource' })
  }

  // Tile
  const tilePath = join(METTASCOPE_DATA, 'tile.png')
  if (existsSync(tilePath)) sources.push({ path: tilePath, name: 'tile', category: 'terrain' })

  console.log(`Found ${sources.length} sprites`)
  return sources
}

async function buildAtlas () {
  const sprites = await findSprites()
  const rows = Math.ceil(sprites.length / COLS)
  const atlasW = COLS * TILE_SIZE
  const atlasH = rows * TILE_SIZE

  console.log(`Atlas: ${atlasW}x${atlasH} (${COLS} cols, ${rows} rows, ${TILE_SIZE}px tiles)`)

  // Downscale each sprite
  const tiles: { input: Buffer, left: number, top: number }[] = []
  const manifest: SpriteEntry[] = []

  for (let i = 0; i < sprites.length; i++) {
    const src = sprites[i]
    const col = i % COLS
    const row = Math.floor(i / COLS)
    const x = col * TILE_SIZE
    const y = row * TILE_SIZE

    try {
      const buf = await sharp(src.path)
        .resize(TILE_SIZE, TILE_SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
        .png()
        .toBuffer()

      tiles.push({ input: buf, left: x, top: y })
      manifest.push({ name: src.name, x, y, w: TILE_SIZE, h: TILE_SIZE, category: src.category })
    } catch (e) {
      console.warn(`Failed to process ${src.name}: ${e}`)
    }
  }

  // Compose atlas
  const atlas = sharp({
    create: { width: atlasW, height: atlasH, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
  }).composite(tiles).png()

  await mkdir(OUTPUT_DIR, { recursive: true })

  const atlasPng = await atlas.toBuffer()
  await writeFile(join(OUTPUT_DIR, 'atlas.png'), atlasPng)

  // Write manifest
  await writeFile(join(OUTPUT_DIR, 'atlas.json'), JSON.stringify(manifest, null, 2))

  // Generate a TS module with the atlas as a base64 data URL + manifest
  const b64 = atlasPng.toString('base64')
  const tsContent = `// Auto-generated by scripts/build-atlas.ts -- do not edit
export const ATLAS_DATA_URL = 'data:image/png;base64,${b64}'

export interface SpriteEntry {
  name: string
  x: number
  y: number
  w: number
  h: number
  category: string
}

export const ATLAS_MANIFEST: SpriteEntry[] = ${JSON.stringify(manifest)}

export const SPRITE_MAP: Record<string, SpriteEntry> = Object.fromEntries(
  ATLAS_MANIFEST.map(s => [s.name, s])
)

export const TILE_SIZE = ${TILE_SIZE}
`
  await writeFile(join(OUTPUT_DIR, 'atlas-data.ts'), tsContent)

  console.log(`Atlas: ${atlasPng.length} bytes (${(atlasPng.length / 1024).toFixed(1)} KB)`)
  console.log(`Manifest: ${manifest.length} sprites`)
  console.log(`Written to ${OUTPUT_DIR}`)
}

buildAtlas().catch(console.error)
